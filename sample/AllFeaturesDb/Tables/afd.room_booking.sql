-- EXCLUDE constraint: no two bookings of the same room may overlap in time.
-- Requires btree_gist so the scalar room_id can sit in a GiST index next to the range.
CREATE TABLE afd.room_booking (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id   integer     NOT NULL,
    during    tstzrange   NOT NULL,
    CONSTRAINT room_no_overlap
        EXCLUDE USING gist (room_id WITH =, during WITH &&)
);
