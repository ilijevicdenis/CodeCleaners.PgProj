-- Flagship table: every common column type, generation strategy and inline constraint.
CREATE TABLE afd.customers (
    -- identity (BY DEFAULT) + composite PK with INCLUDE (see table constraint below)
    id              bigint        GENERATED BY DEFAULT AS IDENTITY,
    tenant_id       integer       NOT NULL DEFAULT 1,

    -- text / character types, one using the custom collation + domain
    email           afd.email     NOT NULL,
    full_name       text          NOT NULL,
    code            char(8),
    short_name      varchar(50)   COLLATE afd.case_insensitive,
    notes           text,

    -- numeric family
    balance_cents   bigint        NOT NULL DEFAULT 0,
    score           numeric(10,2) NOT NULL DEFAULT 0,
    rating          real,
    big_rating      double precision,
    qty             afd.pos_int   DEFAULT 1,
    serial_no       serial,
    big_serial_no   bigserial,

    -- boolean / temporal
    is_active       boolean       NOT NULL DEFAULT true,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    born_on         date,
    wake_time       time,
    duration        interval,

    -- network / bit / uuid / money
    ip_addr         inet,
    mac             macaddr,
    flags           bit(8),
    varflags        bit varying(16),
    ext_id          uuid          DEFAULT gen_random_uuid(),
    wallet          money,

    -- arrays
    tags            text[]        NOT NULL DEFAULT '{}',
    scores          integer[],
    matrix          numeric(6,2)[][],

    -- json / xml
    profile         jsonb         NOT NULL DEFAULT '{}'::jsonb,
    legacy_doc      json,
    xml_doc         xml,

    -- composite / enum / domain / range types
    home            afd.address,
    status          afd.mood      NOT NULL DEFAULT 'ok',
    valid_period    tstzrange,
    temp_range      afd.float_range,

    -- geometric (for the EXCLUDE example elsewhere) + tsvector
    region          circle,
    search          tsvector,

    -- DEFAULT drawing from a sequence
    order_no        bigint        NOT NULL DEFAULT nextval('afd.order_no_seq'),

    -- GENERATED ALWAYS AS STORED (computed column)
    name_upper      text          GENERATED ALWAYS AS (upper(full_name)) STORED,
    balance_dollars numeric(20,2) GENERATED ALWAYS AS (balance_cents / 100.0) STORED,

    -- inline column constraints
    discount        integer       CHECK (discount BETWEEN 0 AND 100),
    referral_email  afd.email     UNIQUE NULLS NOT DISTINCT,

    -- composite primary key with an INCLUDE (non-key) column
    CONSTRAINT customers_pk PRIMARY KEY (tenant_id, id) INCLUDE (email),

    -- named table-level CHECK
    CONSTRAINT customers_score_chk CHECK (score >= 0),

    -- table-level UNIQUE with INCLUDE
    CONSTRAINT customers_email_uq UNIQUE (tenant_id, email) INCLUDE (full_name)
);
