-- Create or replace function afd.touch_updated_at()
CREATE FUNCTION afd.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.created_at := now();
    RETURN NEW;
END;
$$;

-- Create or replace function afd.archive_customer(integer, bigint, boolean)
CREATE PROCEDURE afd.archive_customer(IN p_tenant integer,IN p_id bigint,INOUT moved boolean DEFAULT false) LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO afd.customers_archive
    SELECT now(), c.*
    FROM afd.customers c
    WHERE c.tenant_id = p_tenant AND c.id = p_id;

    DELETE FROM afd.customers c
    WHERE c.tenant_id = p_tenant AND c.id = p_id;

    moved := FOUND;
END;
$$;

